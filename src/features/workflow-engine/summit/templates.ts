import type { ManifestSchema, WorkflowPhase } from '../phase-types.js';
import * as fs from 'fs-extra';
import * as path from 'path';

/**
 * Operations Phase Templates
 *
 * Template-based artifact generation for the Operations (deployment/operations) phase.
 * v1: documentation generation only, no actual deployment.
 */

export interface OperationsContext {
  workflowId: string;
  featureName: string;
  manifest: ManifestSchema | null;
  specContent: string | null;
  buildLogContent: string | null;
  depthLevel: 'SHALLOW' | 'MEDIUM' | 'DEEP';
}

/** @deprecated Use OperationsContext */
export type SummitContext = OperationsContext;

/**
 * Generate deployment guide markdown
 */
export function generateDeployGuide(context: OperationsContext): string {
  const { featureName, workflowId, manifest } = context;
  const timestamp = new Date().toISOString();
  const totalArtifacts = manifest?.artifacts?.length ?? 0;
  const inceptionArtifacts = manifest?.artifacts?.filter(a => a.phase === 'inception').length ?? 0;
  const constructionArtifacts = manifest?.artifacts?.filter(a => a.phase === 'construction').length ?? 0;

  return `---
id: DEPLOY-GUIDE-001
feature: ${workflowId}
created: ${timestamp}
phase: operations
stage: deploy
---

# Deployment Guide: ${featureName}

## Overview

This deployment guide documents the deployment process for ${featureName}.
Generated from ${totalArtifacts} artifacts (${inceptionArtifacts} Inception, ${constructionArtifacts} Construction).

## Pre-Deployment Checklist

- [ ] All Inception artifacts validated and approved
- [ ] All Construction artifacts built and tested
- [ ] Integration tests passing
- [ ] Code review completed
- [ ] Security scan passed
- [ ] Performance benchmarks met

## Deployment Steps

### 1. Pre-Deployment

1. Verify all quality gates have been passed
2. Confirm deployment window with stakeholders
3. Prepare rollback plan
4. Notify affected teams

### 2. Deployment Execution

1. Deploy database migrations (if applicable)
2. Deploy backend services
3. Deploy frontend assets
4. Verify health checks
5. Run smoke tests

### 3. Post-Deployment

1. Monitor error rates for 30 minutes
2. Verify key user flows
3. Check performance metrics
4. Confirm with stakeholders

## Rollback Procedure

1. Identify deployment issue
2. Execute rollback for affected services
3. Verify system stability
4. Investigate root cause
5. Document incident

## Environment Configuration

| Environment | Purpose | Deployment Method |
|-------------|---------|-------------------|
| Development | Feature development | Automatic on merge |
| Staging | Pre-production testing | Manual trigger |
| Production | Live users | Manual approval |

---
*Generated by Operations Phase Templates*
`;
}

